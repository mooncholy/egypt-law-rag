"""Write the query-drift baseline (Phase 14) and check it on an off-topic set.

Embeds the retrieval eval set's questions with the pinned embedder (as the
``models`` service does), writes their centroid and spread to
``docs/metrics/drift_baseline.json``, which the API loads, and reports in
``docs/reports/drift.md`` the ratio of the eval set itself, of each half, and
of family-law questions, which Egypt's personal status law governs, not the
Civil Code (U41 on the real embedder).

Run as ``uv run python scripts/drift_baseline.py`` (CPU is enough: 142 questions).
"""

import argparse
import logging
from pathlib import Path

from raglaw.config import Settings
from raglaw.monitoring.drift import DriftBaseline, Z
from raglaw.retrieval.embeddings import huggingface_embeddings
from raglaw.retrieval.scoring import read_questions, split_questions

logger = logging.getLogger("drift_baseline")

WINDOW = 20  # the API's window, for the reported alert line
FAMILY_LAW = [
    "What are the conditions for a valid marriage contract in Egypt?",
    "How long is the waiting period (idda) after a divorce?",
    "Who gets custody of the children after a divorce, and until what age?",
    "How is alimony (nafaqa) for a divorced wife calculated?",
    "Can a wife ask for khul' without her husband's consent?",
    "How is an inheritance divided between sons and daughters?",
    "ما هي شروط صحة عقد الزواج؟",
    "كم مدة عدة المطلقة؟",
    "لمن تكون حضانة الأطفال بعد الطلاق وحتى أي سن؟",
    "كيف تحسب نفقة الزوجة المطلقة؟",
    "هل يحق للزوجة طلب الخلع دون موافقة الزوج؟",
    "كيف يقسم الميراث بين الأبناء والبنات؟",
]


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    settings = Settings()
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--device", default="cpu")
    args = ap.parse_args()
    questions = read_questions(Path(settings.paths.gold_dir) / "retrieval_eval.jsonl")
    embeddings = huggingface_embeddings(settings.embedding, args.device)
    vectors = embeddings.embed_documents([q.question for q in questions])
    baseline = DriftBaseline.from_vectors(vectors)
    out = Path(settings.paths.metrics_dir) / "drift_baseline.json"
    baseline.save(out)
    halves = split_questions(questions)
    by_id = {q.id: v for q, v in zip(questions, vectors, strict=True)}
    rows = [
        ("eval set (all)", len(vectors), baseline.ratio(vectors)),
        *(
            (
                f"eval set, {name} half",
                len(qs),
                baseline.ratio([by_id[q.id] for q in qs]),
            )
            for name, qs in halves.items()
        ),
        (
            "family law (off-topic)",
            len(FAMILY_LAW),
            baseline.ratio(embeddings.embed_documents(FAMILY_LAW)),
        ),
    ]
    lines = [
        "# Query drift baseline",
        "",
        (
            f"Generated by `scripts/drift_baseline.py`: {baseline.questions} eval "
            f"questions embedded with {settings.embedding.model}. Their mean cosine to "
            f"the centroid is {baseline.mean:.4f} (standard deviation {baseline.std:.4f}). "
            "A window's drift is its mean cosine over that mean; the alert line for a "
            f"window of {WINDOW} questions is {Z:g} standard errors below 1: "
            f"**{baseline.threshold(WINDOW):.4f}**."
        ),
        "",
        "| Questions | Count | Drift ratio |",
        "| --- | --- | --- |",
        *(f"| {name} | {n} | {ratio:.4f} |" for name, n, ratio in rows),
    ]
    report = Path(settings.paths.reports_dir) / "drift.md"
    report.write_text("\n".join(lines) + "\n", "utf-8")
    for name, n, ratio in rows:
        logger.info("%s (%d): %.4f", name, n, ratio)
    logger.info("Alert line at %d questions: %.4f", WINDOW, baseline.threshold(WINDOW))


if __name__ == "__main__":
    main()
